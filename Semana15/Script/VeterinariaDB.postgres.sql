/* =====================================================================
   Semana 15 - Versión PostgreSQL de la base VeterinariaDB (para la nube)
   Equivale a VeterinariaDB.sql + 02_Usuarios.sql (SQL Server).
   Cambios respecto a SQL Server:
     - IDENTITY(1,1)           -> GENERATED BY DEFAULT AS IDENTITY
     - NVARCHAR / DATETIME2(0) -> VARCHAR / TIMESTAMP(0)
     - SYSDATETIME()           -> LOCALTIMESTAMP(0)
     - Los nombres van entre comillas dobles porque EF Core los consulta
       respetando mayúsculas ("Propietario", "IdPropietario", ...).
   Ejecutar conectado a la base de datos creada en el proveedor (por ejemplo Neon).
   ===================================================================== */

DROP TABLE IF EXISTS "Mascota";
DROP TABLE IF EXISTS "Usuario";
DROP TABLE IF EXISTS "Propietario";

/* ----------------------------- TABLAS ----------------------------------- */
CREATE TABLE "Propietario" (
    "IdPropietario"  INT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT "PK_Propietario" PRIMARY KEY,
    "Dni"            CHAR(8)        NOT NULL
        CONSTRAINT "UQ_Propietario_Dni" UNIQUE,
    "Nombres"        VARCHAR(100)   NOT NULL,
    "Apellidos"      VARCHAR(100)   NOT NULL,
    "Telefono"       VARCHAR(15)    NOT NULL,
    "Correo"         VARCHAR(120)   NULL,
    "FechaRegistro"  TIMESTAMP(0)   NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE "Mascota" (
    "IdMascota"        INT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT "PK_Mascota" PRIMARY KEY,
    "Nombre"           VARCHAR(50)    NOT NULL,
    "Especie"          VARCHAR(30)    NOT NULL,
    "Raza"             VARCHAR(50)    NULL,
    "FechaNacimiento"  DATE           NOT NULL,
    "Peso"             DECIMAL(5,2)   NOT NULL
        CONSTRAINT "CK_Mascota_Peso" CHECK ("Peso" > 0),
    "IdPropietario"    INT            NOT NULL
        CONSTRAINT "FK_Mascota_Propietario" REFERENCES "Propietario" ("IdPropietario")
);

CREATE INDEX "IX_Mascota_Propietario" ON "Mascota" ("IdPropietario");

CREATE TABLE "Usuario" (
    "IdUsuario"      INT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT "PK_Usuario" PRIMARY KEY,
    "Correo"         VARCHAR(120)   NOT NULL
        CONSTRAINT "UQ_Usuario_Correo" UNIQUE,
    "ClaveHash"      VARCHAR(100)   NOT NULL,
    "Rol"            VARCHAR(20)    NOT NULL DEFAULT 'Recepcionista'
        CONSTRAINT "CK_Usuario_Rol" CHECK ("Rol" IN ('Recepcionista', 'Veterinario')),
    "FechaRegistro"  TIMESTAMP(0)   NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

